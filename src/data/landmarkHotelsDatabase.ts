// Helper to compute haversine distance in km
export function calculateHaversineDistance(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return parseFloat((R * c).toFixed(1));
}

// Convert distance to road driving estimate
export function estimateRoadTravelTime(distanceKm: number): string {
  if (distanceKm <= 0.4) return '2 mins walk (250m)';
  if (distanceKm <= 0.8) return '5 mins walk';
  if (distanceKm <= 1.5) return '4 - 6 mins drive';
  if (distanceKm <= 3.0) return '8 - 12 mins drive';
  if (distanceKm <= 6.0) return '15 - 20 mins drive';
  if (distanceKm <= 12.0) return '25 - 35 mins drive';
  const mins = Math.round(distanceKm * 2.8);
  return `${mins} mins drive`;
}

